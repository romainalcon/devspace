//! Local web server, domains and certificate authority.
//!
//! Every registered project gets a site at `https://<name>.<tld>` (and its
//! subdomains; `internal` by default), served by [Caddy](https://caddyserver.com) running as the
//! current user, supervised by the daemon:
//!
//! - [`release`]: the pinned Caddy release, downloaded and verified
//!   against embedded SHA-256 checksums;
//! - [`site`]: what each project serves (static files or a development
//!   server), from its manifest;
//! - [`caddy_config`]: the Caddy JSON configuration of the sites;
//! - [`ca`]: the local certificate authority generated by Caddy;
//! - [`dns`]: the DNS answers making `*.<tld>` resolve to the loopback
//!   address of the sites.
//!
//! Everything listens on loopback addresses only, on unprivileged ports
//! ([`crate::config::WebConfig`]).

pub mod ca;
pub mod caddy_config;
pub mod dns;
pub mod release;
pub mod site;

use std::path::PathBuf;

use devspace_platform::target::executable_name;

use crate::AppPaths;

/// Files and directories of the web server.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WebLayout {
    /// Caddy executable of the pinned release.
    pub caddy_binary: PathBuf,
    /// Generated Caddy configuration.
    pub caddy_config: PathBuf,
    /// Caddy storage: local certificate authority and site certificates.
    pub caddy_storage: PathBuf,
    /// Home and XDG directories given to the Caddy process, so that it
    /// writes nothing in the user's own directories.
    pub caddy_home: PathBuf,
    /// Output of the Caddy process, truncated at every start.
    pub caddy_log: PathBuf,
    /// Process id of the running Caddy, to stop it after a daemon crash.
    pub caddy_pid_file: PathBuf,
    /// Partial downloads.
    pub download_dir: PathBuf,
}

impl WebLayout {
    /// Layout inside the DevSpace directories.
    #[must_use]
    pub fn new(paths: &AppPaths) -> Self {
        let caddy_dir = paths.data_dir.join("caddy");
        Self {
            caddy_binary: paths
                .data_dir
                .join("tools")
                .join("caddy")
                .join(release::CADDY_VERSION)
                .join(executable_name("caddy")),
            caddy_config: caddy_dir.join("config.json"),
            caddy_storage: caddy_dir.join("storage"),
            caddy_home: caddy_dir.join("home"),
            caddy_log: paths.log_dir.join("caddy.log"),
            caddy_pid_file: paths.runtime_dir.join("caddy.pid"),
            download_dir: paths.cache_dir.join("downloads"),
        }
    }

    /// Root certificate of the local certificate authority, created by
    /// Caddy on its first start.
    #[must_use]
    pub fn ca_root_certificate(&self) -> PathBuf {
        self.caddy_storage
            .join("pki")
            .join("authorities")
            .join("local")
            .join("root.crt")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn layout_stays_in_devspace_directories() {
        let paths = AppPaths::from_root(std::path::Path::new("/devspace"));
        let layout = WebLayout::new(&paths);
        assert!(
            layout
                .caddy_binary
                .starts_with("/devspace/data/tools/caddy")
        );
        assert!(layout.caddy_storage.starts_with("/devspace/data/caddy"));
        assert!(layout.caddy_log.starts_with("/devspace/logs"));
        assert!(layout.caddy_pid_file.starts_with("/devspace/run"));
        assert!(layout.download_dir.starts_with("/devspace/cache"));
        assert!(
            layout
                .ca_root_certificate()
                .starts_with(&layout.caddy_storage)
        );
    }
}
